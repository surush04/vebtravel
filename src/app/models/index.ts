// ---- Language --------------------------------------------------------
export type LanguageCode = 'tg' | 'ru' | 'en';

export interface LanguageOption {
  code: LanguageCode;
  /** Short label shown in the switcher (TJ / RU / EN). */
  label: string;
  nativeName: string;
  htmlLang: string;
  ogLocale: string;
}

export type Dictionary = { [key: string]: string | string[] | Dictionary | Dictionary[] };

// ---- Navigation -------------------------------------------------------
export interface NavItem {
  /** Translation key for the label. */
  key: string;
  path: string;
}

// ---- Media ------------------------------------------------------------
export type SceneTone = 'dawn' | 'dusk' | 'mist' | 'forest' | 'night' | 'snow';

/** A photo slot. Real files are registered in /public/images/manifest.json. */
export interface MediaAsset {
  /** Placeholder art shown until a real photograph is provided. */
  scene: { tone: SceneTone; seed: number };
  /** CSS object-position, e.g. "50% 30%". */
  focal?: string;
}

/** Generated by `npm run images` for every processed photograph. */
export interface MediaManifestEntry {
  widths: number[];
  formats: ('avif' | 'webp' | 'jpg')[];
  width: number;
  height: number;
  /** Cache-busting version (set when a photo is replaced in the admin). */
  v?: number;
}

export interface MediaManifest {
  images: Record<string, MediaManifestEntry>;
}

// ---- Content (managed in the admin panel) --------------------------------
/** Texts for an activity live in i18n under `activities.items.<id>`. */
export type ActivityId = string;

export interface Activity {
  id: ActivityId;
  media: string;
}

/** Texts for a destination live in i18n under `destinations.items.<id>`. */
export type DestinationId = string;

export interface Destination {
  id: DestinationId;
  media: string;
}

/** Category labels live in i18n under `gallery.categories.<id>`. */
export type GalleryCategory = string;
export type Orientation = 'portrait' | 'landscape' | 'square';

export interface GalleryItem {
  id: string;
  media: string;
  category: GalleryCategory;
  orientation: Orientation;
}

// ---- Contact -------------------------------------------------------------
export interface ContactPayload {
  name: string;
  email: string;
  phone: string;
  country: string;
  activity: ActivityId | 'other' | '';
  message: string;
  language: LanguageCode;
}

export type ContactResult = 'sent' | 'whatsapp' | 'unconfigured' | 'error';

// ---- Editable site content (served by /api/content) -------------------------
export interface SiteSettings {
  established: number;
  siteUrl: string;
  contact: { email: string | null; phone: string | null; whatsapp: string | null };
  location: { mapEmbedUrl: string | null; mapLink: string | null };
  regionMap: { embedUrl: string; link: string };
  social: { id: SocialId; url: string | null }[];
  heroVideo: { mp4: string | null; webm: string | null };
}

export interface SiteContent {
  settings: SiteSettings;
  activities: Activity[];
  destinations: Destination[];
  galleryCategories: GalleryCategory[];
  gallery: GalleryItem[];
}

export type LangDictionaries = Record<LanguageCode, Dictionary>;

export interface ContentPayload {
  site: SiteContent;
  i18n: LangDictionaries;
  media: MediaManifest;
}

// ---- Site configuration ----------------------------------------------------
export type SocialId = 'instagram' | 'facebook' | 'youtube' | 'telegram';

export interface SiteConfig {
  name: string;
  established: number;
  /** Public origin used for canonical URLs and Open Graph (no trailing slash). */
  siteUrl: string;
  ogImage: string;
  contact: {
    email: string | null;
    phone: string | null;
    /** International format, digits only, e.g. "992XXXXXXXXX". */
    whatsapp: string | null;
  };
  /** Verified office location map (iframe embed URL). Hidden while null. */
  location: { mapEmbedUrl: string | null; mapLink: string | null };
  /** Regional overview map of Darvoz shown on the Destinations section. */
  regionMap: { embedUrl: string; link: string };
  social: { id: SocialId; url: string | null }[];
  /** POST endpoint that accepts JSON (e.g. Formspree, own API). */
  formEndpoint: string | null;
  heroVideo: { mp4: string | null; webm: string | null };
  /** Show the photo-slot name on placeholder images. */
  showImageSlotLabels: boolean;
}
